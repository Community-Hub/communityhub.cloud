import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
mkdirSync('screenshots/oct8-review',{recursive:true});
for (const width of [390,1440]) test(`Oct 8 sources and responsive review at ${width}`,async({page})=>{
  test.setTimeout(90000);
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/#who');
  await expect(page.getByRole('region',{name:'Voices',includeHidden:true})).toHaveAttribute('inert');
  await expect(page.getByRole('region',{name:'Who we are',exact:true}).getByRole('link',{name:'Story of Dashboard',exact:true})).toHaveCount(0);
  await page.screenshot({path:`screenshots/oct8-review/who-${width}.png`});
  await page.goto('/#educate/building/oberlin-public-schools-oberlin-elementary-school');
  const region=page.getByRole('region',{name:'Educate',exact:true});
  await expect(region.locator('[data-slide]:not([aria-hidden]) iframe')).toHaveAttribute('src',/ops\/dashboard\/529$/);
  await expect(region.locator('[data-passive-preview]')).toHaveCount(0);
  await page.waitForTimeout(4000); // allow cross-origin charts to paint for the visual artifact
  await page.screenshot({path:`screenshots/oct8-review/building-${width}.png`});
  await page.goto('/#educate/stories/city-of-oberlin-climate-action-plan');
  await expect(region.locator('[data-slide]:not([aria-hidden]) iframe')).toHaveAttribute('src',/1QFoq6mtnCp7EWP0b8p506PQu8pQBBsbo7gH6C-R6Bcs\/embed\?start=false/);
  await expect(region.locator('[data-passive-preview]')).toHaveCount(1);
  await expect(page.frameLocator('iframe[title="City of Oberlin – Climate Action Plan"]').getByRole('img',{name:/Slide 1 of/}).first()).toBeVisible({timeout:20000});
  await page.screenshot({path:`screenshots/oct8-review/stories-${width}.png`});
  await region.locator('[data-slider-box]').hover();
  await region.getByRole('button',{name:'Next example',exact:true}).click();
  await expect(region.locator('[data-example-title]')).toHaveText('Oberlin Public Schools – Energy Use');
  await region.getByRole('button',{name:'Next example',exact:true}).click();
  await expect(region.locator('[data-example-title]')).toHaveText('Great Lakes Science Center – Climate');
  await page.goto('/#engage/embed/great-lakes-science-center-environmental-dashboard');
  const engage=page.getByRole('region',{name:'Engage',exact:true});
  await expect(engage.locator('[data-example-title]')).toHaveText('Great Lakes Science Center – Environmental dashboard');
  await expect(engage.locator('[data-passive-preview]')).toHaveCount(1);
  await page.waitForTimeout(3000);
  await page.screenshot({path:`screenshots/oct8-review/embed-${width}.png`});
  await page.goto('/#motivate/voices');
  const motivate=page.getByRole('region',{name:'Motivate and Empower',exact:true});
  await expect(motivate.locator('iframe')).toHaveAttribute('src',/portrait-mode=0/);
  await page.waitForTimeout(3000);
  await page.screenshot({path:`screenshots/oct8-review/voices-${width}.png`});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect(errors).toEqual([]);
});
